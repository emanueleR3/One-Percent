#!/usr/bin/env python3
"""Rebuilds Resources/en.lproj and Resources/it.lproj from the keys used in the Swift sources.

English text is the key. The Italian table lives in Scripts/translations-it.py; any key missing
from it is reported and left out, so the app falls back to English instead of showing nothing.

    python3 Scripts/generate-strings.py
"""
import importlib.util
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = [
    os.path.join(ROOT, "Sources", "OnePercent"),
    os.path.join(ROOT, "Sources", "OnePercentCore"),
    os.path.join(ROOT, "iOS", "OnePercentiOS"),
]


def used_keys():
    keys = set()
    for source in SOURCES:
        for directory, _, files in os.walk(source):
            for name in files:
                if not name.endswith(".swift") or name == "Localizer.swift":
                    continue
                text = open(os.path.join(directory, name), encoding="utf-8").read()
                for m in re.finditer(r'\bL\("((?:[^"\\]|\\.)*)"', text):
                    keys.add(m.group(1))
                for m in re.finditer(r'\bLp\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"', text):
                    keys.update(m.groups())
    return keys


def unescape_swift(text):
    return text.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def escape_strings(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write(path, table):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("/* Generated by Scripts/generate-strings.py. English text is the key. */\n")
        for key in sorted(table):
            handle.write(f'"{escape_strings(key)}" = "{escape_strings(table[key])}";\n')


def main():
    spec = importlib.util.spec_from_file_location("translations_it", os.path.join(ROOT, "Scripts", "translations-it.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    italian = module.IT

    keys = {unescape_swift(k) for k in used_keys()}
    missing = sorted(k for k in keys if k not in italian)
    stale = sorted(k for k in italian if k not in keys)

    write(os.path.join(ROOT, "Resources", "en.lproj", "Localizable.strings"), {k: k for k in keys})
    write(os.path.join(ROOT, "Resources", "it.lproj", "Localizable.strings"), {k: v for k, v in italian.items() if k in keys})

    print(f"{len(keys)} keys, {len(keys) - len(missing)} translated to Italian")
    for k in missing:
        print("  missing:", k)
    for k in stale:
        print("  stale (unused):", k)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
